/**
 * The logo centred on the 720×129 aspect the OpenCode wordmark had, so every place sized for it (the new session
 * hero, the first-launch splash, the connect screen) keeps its layout. `outline` strokes every shape for the splash
 * to draw, `muted` fades it; there is no `fade` gradient.
 */
export function BrandWordmark(
  props: Pick<ComponentProps<"svg">, "class"> & { fade?: boolean; muted?: boolean; outline?: boolean },
) {
  return (
    <svg
      data-component="brand-logo"
      classList={{
        [props.class ?? ""]: !!props.class,
        "overflow-visible [&_path]:[vector-effect:non-scaling-stroke]": props.outline,
      }}
      viewBox="-152.2 -7 625.1 112"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
    >
      <g opacity={props.muted === false || props.outline ? 1 : 0.4} transform="translate(0.774194 0.612903)">
        <Artwork text outline={props.outline} />
      </g>
    </svg>
  )
}
